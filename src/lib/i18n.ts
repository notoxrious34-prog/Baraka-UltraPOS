/**
 * Translate a backend wire error code. Handles `ACCOUNT_LOCKED:<secs>`.
 * Unknown codes fall back to INTERNAL_ERROR (never leaks raw text).
 */
export function translateBackendError(raw: unknown, locale: Locale): string {
  const table = locale === "ar-DZ" ? arErrors : frErrors;
  const fallback = table["INTERNAL_ERROR"] ?? "Error";
  if (typeof raw !== "string") {
    return fallback;
  }
  const code = raw.trim();
  if (code.startsWith("ACCOUNT_LOCKED:")) {
    const seconds = code.slice("ACCOUNT_LOCKED:".length).trim();
    const template = table["ACCOUNT_LOCKED"] ?? fallback;
    return template.replace("{seconds}", seconds === "" ? "…" : seconds);
  }
  return table[code] ?? fallback;
}
