// docs/architecture/tools/build-boot-package.mjs - deterministic boot-package generator.
// Concatenates CHARTER-v2.0.md + current CTP + up to 2 preceding CTPs, byte for
// byte, into BOOT-SESSION-ARC-00N.md (session tag derived from the --ctp basename).
// Node built-ins only. No timestamps, no env-dependent content.
// Usage: node docs/architecture/tools/build-boot-package.mjs [--charter <p>] [--ctp <p>] [--out <p>] [--check] [--prev1 <p>] [--prev2 <p>] [--history <n>]
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const archDir = path.dirname(scriptDir);

function arg(name, def) {
  const i = process.argv.indexOf(name);
  if (i >= 0 && process.argv[i + 1] && !process.argv[i + 1].startsWith('--')) return path.resolve(process.argv[i + 1]);
  return def;
}

function argVal(name, def) {
  const i = process.argv.indexOf(name);
  if (i >= 0 && process.argv[i + 1] && !process.argv[i + 1].startsWith('--')) return process.argv[i + 1];
  return def;
}

const checkOnly = process.argv.includes('--check');
const charterPath = arg('--charter', path.join(archDir, 'CHARTER-v2.0.md'));
const ctpPath = arg('--ctp', path.join(archDir, 'CTP-SESSION-ARC-002.md'));
const outPath = arg('--out', path.join(archDir, 'BOOT-SESSION-ARC-002.md'));
const historyDepth = Math.max(0, parseInt(argVal('--history', '2'), 10) || 0);

// Session tag derived from the CTP basename (CTP-SESSION-ARC-003.md -> ARC-003).
// Defaults keep the ARC-002 output byte-identical.
const ctpBase = path.basename(ctpPath);
const tagMatch = ctpBase.match(/^CTP-SESSION-(ARC-\d+)\.md$/);
const TAG = tagMatch ? tagMatch[1] : 'ARC-002';
const SESSION = 'SESSION-' + TAG;

// Current session number for prior-session auto-discovery.
const numMatch = ctpBase.match(/^CTP-SESSION-ARC-(\d+)\.md$/);
const currentNum = numMatch ? parseInt(numMatch[1], 10) : null;

// Prior CTPs: explicit --prev1/--prev2 override, else auto-discover up to
// --history sessions back. Missing files degrade gracefully (skipped).
const priors = [];
for (let k = 1; k <= historyDepth; k++) {
  const override = argVal('--prev' + k, null);
  let prevPath = null;
  if (override) {
    prevPath = path.resolve(override);
  } else if (currentNum !== null && currentNum - k >= 1) {
    const filename = 'CTP-SESSION-ARC-' + String(currentNum - k).padStart(3, '0') + '.md';
    prevPath = path.join(archDir, filename);
  }
  if (prevPath !== null && fs.existsSync(prevPath)) {
    priors.push({ path: prevPath, base: path.basename(prevPath) });
  }
}

const prevLines = priors.map((p, i) => `  PART ${i + 3}: docs/architecture/${p.base} (preceding session CTP)`);
const PREAMBLE = [
  `# BOOT PACKAGE - ${SESSION} (a successor architect session starts here)`,
  '',
  'This single file is generated by docs/architecture/tools/build-boot-package.mjs. It concatenates, byte for byte and in this order:',
  '  PART 1: docs/architecture/CHARTER-v2.0.md (the binding charter)',
  `  PART 2: docs/architecture/${ctpBase} (current session state, decisions, roadmap)`,
  ...prevLines,
  '',
  '=====BEGIN-PART-1-CHARTER=====',
].join('\n') + '\n';

const MARK_END_1 = '=====END-PART-1-CHARTER=====\n';
const MARK_BEGIN_2 = `=====BEGIN-PART-2-CURRENT-CTP-${TAG}=====\n`;
const MARK_END_2 = `=====END-PART-2-CURRENT-CTP-${TAG}=====\n`;

const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');

function withSeparator(buf) {
  if (buf.length > 0 && buf[buf.length - 1] === 0x0a) return { buf, added: 0 };
  return { buf: Buffer.concat([buf, Buffer.from([0x0a])]), added: 1 };
}

const charterRaw = fs.readFileSync(charterPath);
const ctpRaw = fs.readFileSync(ctpPath);
const charter = withSeparator(charterRaw);
const ctp = withSeparator(ctpRaw);

const chunks = [
  Buffer.from(PREAMBLE, 'utf8'),
  charter.buf,
  Buffer.from(MARK_END_1, 'utf8'),
  Buffer.from(MARK_BEGIN_2, 'utf8'),
  ctp.buf,
  Buffer.from(MARK_END_2, 'utf8'),
];
const sepAdded = [`charter=${charter.added}`, `ctp=${ctp.added}`];

priors.forEach((p, i) => {
  const partNum = i + 3;
  const prevTagMatch = p.base.match(/^CTP-SESSION-(ARC-\d+)\.md$/);
  const prevTag = prevTagMatch ? prevTagMatch[1] : p.base;
  const raw = fs.readFileSync(p.path);
  const prev = withSeparator(raw);
  chunks.push(Buffer.from(`=====BEGIN-PART-${partNum}-PRIOR-CTP-${prevTag}=====\n`, 'utf8'));
  chunks.push(prev.buf);
  chunks.push(Buffer.from(`=====END-PART-${partNum}-PRIOR-CTP-${prevTag}=====\n`, 'utf8'));
  sepAdded.push(`prev${i + 1}=${prev.added}`);
  console.log(`prev${i + 1}: ${p.base} ${raw.length} B sha256=${sha(raw)}`);
});

const out = Buffer.concat(chunks);

console.log(`charter: ${charterRaw.length} B sha256=${sha(charterRaw)}`);
console.log(`ctp: ${ctpRaw.length} B sha256=${sha(ctpRaw)}`);
console.log(`added separator LFs: ${sepAdded.join(' ')}`);
console.log(`output: ${out.length} B sha256=${sha(out)}`);

if (checkOnly) {
  let disk = null;
  try { disk = fs.readFileSync(outPath); } catch { /* missing */ }
  if (disk !== null && disk.equals(out)) { console.log('CHECK: OK'); process.exit(0); }
  console.log('CHECK: DIFFERENT'); process.exit(1);
}

fs.writeFileSync(outPath, out);
console.log(`wrote ${outPath}`);
