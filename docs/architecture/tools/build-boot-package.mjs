// docs/architecture/tools/build-boot-package.mjs - deterministic boot-package generator.
// Concatenates CHARTER-v2.0.md + CTP-SESSION-ARC-00N.md byte for byte into
// BOOT-SESSION-ARC-00N.md (session tag derived from the --ctp basename).
// Node built-ins only. No timestamps, no env-dependent content.
// Usage: node docs/architecture/tools/build-boot-package.mjs [--charter <p>] [--ctp <p>] [--out <p>] [--check]
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const archDir = path.dirname(scriptDir);

function arg(name, def) {
  const i = process.argv.indexOf(name);
  if (i >= 0 && process.argv[i + 1] && !process.argv[i + 1].startsWith('--')) return path.resolve(process.argv[i + 1]);
  return def;
}

const checkOnly = process.argv.includes('--check');
const charterPath = arg('--charter', path.join(archDir, 'CHARTER-v2.0.md'));
const ctpPath = arg('--ctp', path.join(archDir, 'CTP-SESSION-ARC-002.md'));
const outPath = arg('--out', path.join(archDir, 'BOOT-SESSION-ARC-002.md'));

// Session tag derived from the CTP basename (CTP-SESSION-ARC-003.md -> ARC-003).
// Defaults keep the ARC-002 output byte-identical.
const ctpBase = path.basename(ctpPath);
const tagMatch = ctpBase.match(/^CTP-SESSION-(ARC-\d+)\.md$/);
const TAG = tagMatch ? tagMatch[1] : 'ARC-002';
const SESSION = 'SESSION-' + TAG;

const PREAMBLE = [
  `# BOOT PACKAGE - ${SESSION} (a successor architect session starts here)`,
  '',
  'This single file is generated by docs/architecture/tools/build-boot-package.mjs. It concatenates, byte for byte and in this order:',
  '  PART 1: docs/architecture/CHARTER-v2.0.md (the binding charter)',
  `  PART 2: docs/architecture/${ctpBase} (state, decisions, evidence, roadmap, reply log)`,
  '',
  'Instructions for the new architect session: read PART 1 completely, then PART 2. Section 12 of PART 2 gives the reply number to continue from. The older package SESSION-ARC-001 is NOT included; it lives in the repo at docs/architecture/CTP-SESSION-ARC-001.md and can be requested through a read-only task. If any Arabic text below appears garbled, tell the owner and do not guess its content.',
  '',
  '=====BEGIN-PART-1-CHARTER=====',
].join('\n') + '\n';

const MARK_END_1 = '=====END-PART-1-CHARTER=====\n';
const MARK_BEGIN_2 = `=====BEGIN-PART-2-CTP-${TAG}=====\n`;
const MARK_END_2 = `=====END-PART-2-CTP-${TAG}=====\n`;

const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');

function withSeparator(buf) {
  if (buf.length > 0 && buf[buf.length - 1] === 0x0a) return { buf, added: 0 };
  return { buf: Buffer.concat([buf, Buffer.from([0x0a])]), added: 1 };
}

const charterRaw = fs.readFileSync(charterPath);
const ctpRaw = fs.readFileSync(ctpPath);
const charter = withSeparator(charterRaw);
const ctp = withSeparator(ctpRaw);

const out = Buffer.concat([
  Buffer.from(PREAMBLE, 'utf8'),
  charter.buf,
  Buffer.from(MARK_END_1, 'utf8'),
  Buffer.from(MARK_BEGIN_2, 'utf8'),
  ctp.buf,
  Buffer.from(MARK_END_2, 'utf8'),
]);

console.log(`charter: ${charterRaw.length} B sha256=${sha(charterRaw)}`);
console.log(`ctp: ${ctpRaw.length} B sha256=${sha(ctpRaw)}`);
console.log(`added separator LFs: charter=${charter.added} ctp=${ctp.added}`);
console.log(`output: ${out.length} B sha256=${sha(out)}`);

if (checkOnly) {
  let disk = null;
  try { disk = fs.readFileSync(outPath); } catch { /* missing */ }
  if (disk !== null && disk.equals(out)) { console.log('CHECK: OK'); process.exit(0); }
  console.log('CHECK: DIFFERENT'); process.exit(1);
}

fs.writeFileSync(outPath, out);
console.log(`wrote ${outPath}`);
